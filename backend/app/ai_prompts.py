def user_message(task_text: str, sources: dict[str, str], request: str = "") -> str:
    parts = [task_text]
    if request:
        parts.append(f"[요청]\n{request}")
    parts += [f"[자료] {title}\n{body}" for title, body in sources.items()]
    return "\n\n".join(parts)


